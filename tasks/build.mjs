/**
 * Composes ready-to-paste /savvy-flow prompts.
 *
 *   node tasks/build.mjs
 *
 * Each prompt is _shared.md followed by one card, so every file stands alone:
 * a CLI session can run any single card with no other context.
 */

import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const shared = readFileSync(join(here, '_shared.md'), 'utf8').trim();
const cardsDir = join(here, 'cards');
const outDir = join(here, 'prompts');

mkdirSync(outDir, { recursive: true });

const cards = readdirSync(cardsDir)
  .filter((f) => f.endsWith('.md'))
  .sort();

const index = [];

for (const file of cards) {
  const card = readFileSync(join(cardsDir, file), 'utf8').trim();
  const title = (card.match(/^## YOUR TASK — (.+)$/m) ?? [, basename(file, '.md')])[1];

  const body = [
    `# /savvy-flow — ${title}`,
    '',
    'Paste everything below the line into the CLI after `/savvy-flow`.',
    '',
    '---',
    '',
    shared,
    '',
    '---',
    '',
    card,
    '',
  ].join('\n');

  const out = join(outDir, file);
  writeFileSync(out, body, 'utf8');
  index.push({ file, title, bytes: Buffer.byteLength(body) });
}

const readme = [
  '# Ready-to-paste CLI prompts',
  '',
  'Generated by `node tasks/build.mjs`. Edit `_shared.md` or `cards/*.md`,',
  'then regenerate. Do not edit these files directly.',
  '',
  'Each file is self-contained. Open one, copy everything below the first',
  'horizontal rule, and paste it into a CLI session after `/savvy-flow`.',
  '',
  '| Prompt | Card | Size |',
  '| --- | --- | --- |',
  ...index.map((r) => `| \`${r.file}\` | ${r.title} | ${(r.bytes / 1024).toFixed(1)} KB |`),
  '',
  '## Suggested order',
  '',
  '**Can run right now, in parallel** — these depend only on contracts that',
  'already exist:',
  '',
  '- `c-packet-importer.md` — pure parsing, no UI',
  '- `d-oac-mode.md` — match logic, builds against the OacPacket type',
  '- `e-ear-training.md` — self-contained, plus an ffmpeg transcode',
  '',
  '**Run after Card A lands:**',
  '',
  '- `a-app-shell.md` — start this one first, everything visual waits on it',
  '- `b-pwa-capacitor.md` — needs the screens to exist',
  '- `f-learn-tab.md` — needs the tab bar, and the owned Misses.tsx for its peak',
  '',
  'Two writers must never touch the same files. Cards C, D and E are disjoint,',
  'so they are safe to run at the same time.',
  '',
].join('\n');

writeFileSync(join(outDir, 'README.md'), readme, 'utf8');

console.log(`wrote ${index.length} prompts to ${outDir}`);
for (const r of index) {
  console.log(`  ${r.file.padEnd(26)} ${(r.bytes / 1024).toFixed(1)} KB  ${r.title}`);
}
